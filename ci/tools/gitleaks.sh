# gitleaks — секреты в истории git, а не в рабочем дереве. Это отдельная
# проверка, а не дубль trivy: секрет, закоммиченный и удалённый следующим
# коммитом, из дерева исчезает, а из истории нет, и он по-прежнему
# скомпрометирован. Заметить его можно только так.
#
# ВАЖНО: в GitHub Actions actions/checkout по умолчанию делает fetch-depth: 1,
# и история состоит из одного коммита. Пайплайн выставляет fetch-depth: 0 сам,
# но при копировании шагов в свой workflow это первое, что теряется.
tool_run() {
	bin_tool gitleaks >/dev/null || { bad "gitleaks не найден в PATH"; return 1; }
	[ -d "$SEC_SRC/.git" ] || { bad "gitleaks: не git-репозиторий, историю смотреть негде"; return 1; }
	set -- gitleaks git --no-banner --exit-code 0 \
		--report-format json --report-path "$OUT_JSON"
	# Значения найденных секретов в отчёт не попадают. Находка и без них несёт
	# всё нужное — правило, файл, строку, коммит, автора, — а отчёт уезжает в
	# DefectDojo, живёт там годами и виден всем, у кого есть доступ. Класть
	# рабочий ключ в трекер, чтобы потом вычищать его оттуда, — плохой размен.
	[ "${SEC_GITLEAKS_REDACT:-1}" = "1" ] && set -- "$@" --redact
	# shellcheck disable=SC2086
	set -- "$@" $ARGS "$SEC_SRC"
	"$@"
}

tool_norm() {
	# У gitleaks нет шкалы: правило либо сработало, либо нет. Любой найденный
	# секрет — high. Ложные срабатывания лечатся .gitleaksignore в проекте,
	# а не понижением важности всей категории.
	jq '[.[]? | {
		severity: "high",
		rule: .RuleID,
		title: (.Description + " (" + (.Commit[0:8] // "рабочее дерево") + ", " + (.Author // "?") + ")"),
		file: .File,
		line: (.StartLine // 0),
		extra: (.Date // "")
	}]' "$OUT_JSON"
}
