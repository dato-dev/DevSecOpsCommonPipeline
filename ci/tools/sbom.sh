# SBOM — состав зависимостей в CycloneDX. Не находки, а инвентарь: он отвечает
# на вопрос «у нас вообще есть log4j?» в тот день, когда про log4j спрашивают,
# а не через неделю пересканирования всех репозиториев.
#
# --scanners vuln здесь обязателен, и это неочевидно: у trivy формат cyclonedx
# ВЫКЛЮЧАЕТ поиск уязвимостей, и без флага в BOM нет секции vulnerabilities.
# А парсер DefectDojo строит находки только из неё — компоненты сами по себе
# попадают в инвентарь лишь при включённом V3_FEATURE_LOCATIONS, которого в
# OSS-установке по умолчанию нет. Без флага SBOM залился бы «успешно» и не дал
# ровно ничего видимого.
tool_run() {
	bin_tool trivy >/dev/null || { bad "trivy не найден в PATH"; return 1; }
	# shellcheck disable=SC2086
	trivy fs --quiet --format cyclonedx --output "$OUT_JSON" \
		--scanners vuln $ARGS "$SEC_SRC"
}

tool_norm() {
	# Пусто намеренно. Уязвимости из SBOM — это те же самые, что уже нашёл
	# trivy-fs: он и SBOM смотрят одни и те же lock-файлы одной и той же базой.
	# Считать их дважды значит удвоить числа в сводке и в пороге на ровном
	# месте. В DefectDojo SBOM всё равно уезжает — в свой engagement, где
	# дедупликация разведёт его с обычным отчётом.
	echo '[]'
}
